def get_ui_text(key: str, lang: str = "en") -> str:
    """Return a translated UI string for the given key and language code."""
    return UI_TRANSLATIONS.get(lang, UI_TRANSLATIONS["en"]).get(key, key)


def translate_disease_name(disease: str, lang: str = "en") -> str:
    """Translate a disease class name to the target language."""
    return DISEASE_NAME_TRANSLATIONS.get(disease, {}).get(lang, disease)


def translate_severity(severity: str, lang: str = "en") -> str:
    """Translate a severity level label to the target language."""
    return SEVERITY_TRANSLATIONS.get(severity, {}).get(lang, severity)
